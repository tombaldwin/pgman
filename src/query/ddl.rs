//! The schema browser's DDL copy (`d`): a table's (or view's) `CREATE`
//! statement, rebuilt from the catalog.
//!
//! [`fetch`] reads the pieces — columns with their defaults, identity
//! and generation, the table's own constraints, the indexes that don't
//! back a constraint, a partition's bound, a view's definition — with
//! the server doing the quoting (`format('%I.%I')`, `quote_ident`) and
//! the definitions (`pg_get_constraintdef`, `pg_get_indexdef`,
//! `pg_get_viewdef`), so they come back exactly as Postgres would
//! write them. [`create_statement`] assembles them and is pure.
//!
//! Not a `pg_dump`: ownership, grants, comments, triggers, storage
//! parameters and the sequences behind non-serial defaults are left
//! out. It is the statement an engineer pastes to recreate the shape.

use std::sync::Arc;

/// One column, its name already quoted where it needs to be.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct DdlColumn {
    pub name: String,
    pub type_name: String,
    pub not_null: bool,
    /// `pg_get_expr` of the default; for a generated column, its
    /// expression.
    pub default: Option<String>,
    /// `a` (`ALWAYS`) or `d` (`BY DEFAULT`) for an identity column.
    pub identity: Option<char>,
    /// A `GENERATED ALWAYS AS (…) STORED` column.
    pub generated: bool,
    /// The column owns a sequence (`pg_depend` deptype `a`): with a
    /// `nextval` default on an integer type, that is a `serial`.
    pub owns_sequence: bool,
}

/// What kind of relation, as far as the statement's shape goes.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DdlKind {
    Table,
    /// `PARTITION OF parent FOR VALUES …`: the parent, quoted, and the
    /// bound as `pg_get_expr(relpartbound)` writes it.
    Partition {
        parent: String,
        bound: String,
    },
    /// `pg_get_viewdef`.
    View {
        definition: String,
        materialized: bool,
    },
}

/// Everything [`create_statement`] needs.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TableDdl {
    /// `schema.table`, each part quoted where it needs to be.
    pub qualified_name: String,
    pub kind: DdlKind,
    pub columns: Vec<DdlColumn>,
    /// `(quoted name, pg_get_constraintdef)`, primary key first.
    pub constraints: Vec<(String, String)>,
    /// `pg_get_partkeydef` when the table is itself partitioned.
    pub partition_key: Option<String>,
    /// `pg_get_indexdef` of each index no constraint owns.
    pub indexes: Vec<String>,
}

/// The `serial` spelling of an integer column whose default draws from
/// the sequence it owns, or `None`.
fn serial_type(c: &DdlColumn) -> Option<&'static str> {
    let draws = c
        .default
        .as_deref()
        .is_some_and(|d| d.starts_with("nextval("));
    if !(c.owns_sequence && draws && c.identity.is_none()) {
        return None;
    }
    match c.type_name.as_str() {
        "integer" => Some("serial"),
        "bigint" => Some("bigserial"),
        "smallint" => Some("smallserial"),
        _ => None,
    }
}

fn column_line(c: &DdlColumn) -> String {
    let mut line = format!("    {} ", c.name);
    match serial_type(c) {
        Some(serial) => line.push_str(serial),
        None => {
            line.push_str(&c.type_name);
            match (c.identity, c.generated, c.default.as_deref()) {
                (Some('a'), ..) => line.push_str(" GENERATED ALWAYS AS IDENTITY"),
                (Some(_), ..) => line.push_str(" GENERATED BY DEFAULT AS IDENTITY"),
                (None, true, Some(expr)) => {
                    line.push_str(&format!(" GENERATED ALWAYS AS ({expr}) STORED"))
                }
                (None, false, Some(default)) => line.push_str(&format!(" DEFAULT {default}")),
                _ => {}
            }
        }
    }
    if c.not_null {
        line.push_str(" NOT NULL");
    }
    line
}

/// The `CREATE` statement(s) for `ddl`: the table (or view) itself,
/// then one `CREATE INDEX` per index no constraint owns. Pure.
pub fn create_statement(ddl: &TableDdl) -> String {
    let name = &ddl.qualified_name;
    if let DdlKind::View {
        definition,
        materialized,
    } = &ddl.kind
    {
        let body = definition.trim().trim_end_matches(';').trim_end();
        let kind = if *materialized {
            "MATERIALIZED VIEW"
        } else {
            "VIEW"
        };
        let mut out = format!("CREATE {kind} {name} AS\n{body};\n");
        for ix in &ddl.indexes {
            out.push_str(&format!("\n{ix};\n"));
        }
        return out;
    }
    let constraint_lines = ddl
        .constraints
        .iter()
        .map(|(n, def)| format!("    CONSTRAINT {n} {def}"));
    let mut out = match &ddl.kind {
        DdlKind::Partition { parent, bound } => {
            // A partition's columns are its parent's; only its own
            // constraints go in the parentheses, and those only if any.
            let own: Vec<String> = constraint_lines.collect();
            let mut s = format!("CREATE TABLE {name} PARTITION OF {parent}");
            if !own.is_empty() {
                s.push_str(&format!(" (\n{}\n)", own.join(",\n")));
            }
            s.push_str(&format!("\n    {bound}"));
            s
        }
        _ => {
            let body: Vec<String> = ddl
                .columns
                .iter()
                .map(column_line)
                .chain(constraint_lines)
                .collect();
            format!("CREATE TABLE {name} (\n{}\n)", body.join(",\n"))
        }
    };
    if let Some(key) = &ddl.partition_key {
        out.push_str(&format!(" PARTITION BY {key}"));
    }
    out.push_str(";\n");
    for ix in &ddl.indexes {
        out.push_str(&format!("\n{ix};\n"));
    }
    out
}

const RELATION_SQL: &str = "\
SELECT c.oid, c.relkind::text, format('%I.%I', n.nspname, c.relname), \
       CASE WHEN c.relkind = 'p' THEN pg_catalog.pg_get_partkeydef(c.oid) END, \
       (SELECT format('%I.%I', pn.nspname, p.relname) FROM pg_catalog.pg_inherits h \
          JOIN pg_catalog.pg_class p ON p.oid = h.inhparent \
          JOIN pg_catalog.pg_namespace pn ON pn.oid = p.relnamespace \
         WHERE h.inhrelid = c.oid AND c.relispartition), \
       CASE WHEN c.relispartition THEN pg_catalog.pg_get_expr(c.relpartbound, c.oid) END, \
       CASE WHEN c.relkind IN ('v', 'm') THEN pg_catalog.pg_get_viewdef(c.oid, true) END \
FROM pg_catalog.pg_class c \
JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace \
WHERE n.nspname = $1 AND c.relname = $2";

const COLUMNS_SQL: &str = "\
SELECT quote_ident(a.attname), pg_catalog.format_type(a.atttypid, a.atttypmod), a.attnotnull, \
       pg_catalog.pg_get_expr(d.adbin, d.adrelid), a.attidentity::text, a.attgenerated::text, \
       EXISTS (SELECT 1 FROM pg_catalog.pg_depend dep \
                 JOIN pg_catalog.pg_class s ON s.oid = dep.objid AND s.relkind = 'S' \
                WHERE dep.refobjid = a.attrelid AND dep.refobjsubid = a.attnum \
                  AND dep.classid = 'pg_catalog.pg_class'::regclass AND dep.deptype = 'a') \
FROM pg_catalog.pg_attribute a \
LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum \
WHERE a.attrelid = $1 AND a.attnum > 0 AND NOT a.attisdropped \
ORDER BY a.attnum";

/// The table's own constraints — inherited ones (a partition's copy of
/// its parent's) are the parent's to declare.
const CONSTRAINTS_SQL: &str = "\
SELECT quote_ident(c.conname), pg_catalog.pg_get_constraintdef(c.oid, true) \
FROM pg_catalog.pg_constraint c \
WHERE c.conrelid = $1 AND c.contype IN ('p', 'u', 'f', 'c', 'x') AND c.conislocal \
ORDER BY CASE c.contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'x' THEN 2 WHEN 'c' THEN 3 ELSE 4 END, \
         c.conname";

/// Indexes a constraint doesn't own, and that aren't a partition's copy
/// of an index on its parent.
const INDEXES_SQL: &str = "\
SELECT pg_catalog.pg_get_indexdef(x.indexrelid) \
FROM pg_catalog.pg_index x \
JOIN pg_catalog.pg_class i ON i.oid = x.indexrelid \
WHERE x.indrelid = $1 \
  AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_constraint c WHERE c.conindid = x.indexrelid) \
  AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_inherits h WHERE h.inhrelid = x.indexrelid) \
ORDER BY i.relname";

/// Read `schema.table`'s DDL pieces. Read-only catalog queries; an
/// error is the server's message, ready for the footer.
pub async fn fetch(
    client: &Arc<tokio_postgres::Client>,
    schema: &str,
    table: &str,
) -> Result<TableDdl, String> {
    let err = |e: tokio_postgres::Error| crate::conn::QueryErr::from(e).msg;
    let rel = client
        .query_opt(RELATION_SQL, &[&schema, &table])
        .await
        .map_err(err)?
        .ok_or_else(|| format!("{schema}.{table} isn't in the catalog any more · r reloads"))?;
    let oid: u32 = rel.get(0);
    let relkind: String = rel.get(1);
    let qualified_name: String = rel.get(2);
    let kind = match (relkind.as_str(), rel.get::<_, Option<String>>(4)) {
        ("v" | "m", _) => DdlKind::View {
            definition: rel.get::<_, Option<String>>(6).unwrap_or_default(),
            materialized: relkind == "m",
        },
        (_, Some(parent)) => DdlKind::Partition {
            parent,
            bound: rel.get::<_, Option<String>>(5).unwrap_or_default(),
        },
        ("r" | "p", None) => DdlKind::Table,
        (other, _) => {
            return Err(format!(
                "{qualified_name} is a {} — DDL copy covers tables and views",
                relkind_name(other)
            ))
        }
    };
    let params: [&(dyn tokio_postgres::types::ToSql + Sync); 1] = [&oid];
    let (columns, constraints, indexes) = tokio::join!(
        client.query(COLUMNS_SQL, &params),
        client.query(CONSTRAINTS_SQL, &params),
        client.query(INDEXES_SQL, &params),
    );
    let columns = columns
        .map_err(err)?
        .iter()
        .map(|r| DdlColumn {
            name: r.get(0),
            type_name: r.get(1),
            not_null: r.get(2),
            default: r.get(3),
            identity: r.get::<_, Option<String>>(4).and_then(|s| s.chars().next()),
            generated: r.get::<_, Option<String>>(5).as_deref() == Some("s"),
            owns_sequence: r.get(6),
        })
        .collect();
    let constraints = constraints
        .map_err(err)?
        .iter()
        .map(|r| (r.get(0), r.get(1)))
        .collect();
    let indexes = indexes.map_err(err)?.iter().map(|r| r.get(0)).collect();
    Ok(TableDdl {
        qualified_name,
        kind,
        columns,
        constraints,
        partition_key: rel.get(3),
        indexes,
    })
}

fn relkind_name(relkind: &str) -> &'static str {
    match relkind {
        "f" => "foreign table",
        "S" => "sequence",
        "i" | "I" => "index",
        "c" => "composite type",
        _ => "relation of another kind",
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn col(name: &str, ty: &str, not_null: bool) -> DdlColumn {
        DdlColumn {
            name: name.into(),
            type_name: ty.into(),
            not_null,
            ..DdlColumn::default()
        }
    }

    fn table(columns: Vec<DdlColumn>) -> TableDdl {
        TableDdl {
            qualified_name: "public.orders".into(),
            kind: DdlKind::Table,
            columns,
            constraints: Vec::new(),
            partition_key: None,
            indexes: Vec::new(),
        }
    }

    #[test]
    fn a_table_with_constraints_and_an_index() {
        let mut t = table(vec![
            DdlColumn {
                default: Some("nextval('orders_id_seq'::regclass)".into()),
                owns_sequence: true,
                ..col("id", "bigint", true)
            },
            DdlColumn {
                default: Some("'new'::character varying".into()),
                ..col("status", "character varying(20)", true)
            },
            col("note", "text", false),
        ]);
        t.constraints = vec![
            ("orders_pkey".into(), "PRIMARY KEY (id)".into()),
            (
                "orders_user_fk".into(),
                "FOREIGN KEY (user_id) REFERENCES users(id)".into(),
            ),
        ];
        t.indexes =
            vec!["CREATE INDEX orders_status_idx ON public.orders USING btree (status)".into()];
        assert_eq!(
            create_statement(&t),
            "CREATE TABLE public.orders (\n\
             \x20   id bigserial NOT NULL,\n\
             \x20   status character varying(20) DEFAULT 'new'::character varying NOT NULL,\n\
             \x20   note text,\n\
             \x20   CONSTRAINT orders_pkey PRIMARY KEY (id),\n\
             \x20   CONSTRAINT orders_user_fk FOREIGN KEY (user_id) REFERENCES users(id)\n\
             );\n\
             \n\
             CREATE INDEX orders_status_idx ON public.orders USING btree (status);\n"
        );
    }

    #[test]
    fn serial_needs_an_owned_sequence_a_nextval_default_and_an_integer_type() {
        let owned = |ty: &str, default: &str| DdlColumn {
            default: Some(default.into()),
            owns_sequence: true,
            ..col("id", ty, true)
        };
        let next = "nextval('s'::regclass)";
        assert_eq!(serial_type(&owned("integer", next)), Some("serial"));
        assert_eq!(serial_type(&owned("smallint", next)), Some("smallserial"));
        assert_eq!(serial_type(&owned("numeric", next)), None);
        assert_eq!(serial_type(&owned("integer", "0")), None);
        // A nextval default on a sequence the column doesn't own stays a
        // default: `serial` would create a sequence that isn't the one used.
        let shared = DdlColumn {
            owns_sequence: false,
            ..owned("integer", next)
        };
        assert_eq!(serial_type(&shared), None);
        assert_eq!(
            column_line(&shared),
            "    id integer DEFAULT nextval('s'::regclass) NOT NULL"
        );
    }

    #[test]
    fn identity_and_generated_columns() {
        let always = DdlColumn {
            identity: Some('a'),
            owns_sequence: true,
            ..col("id", "bigint", true)
        };
        assert_eq!(
            column_line(&always),
            "    id bigint GENERATED ALWAYS AS IDENTITY NOT NULL"
        );
        let by_default = DdlColumn {
            identity: Some('d'),
            ..always.clone()
        };
        assert_eq!(
            column_line(&by_default),
            "    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL"
        );
        let generated = DdlColumn {
            default: Some("(price * qty)".into()),
            generated: true,
            ..col("total", "numeric", false)
        };
        assert_eq!(
            column_line(&generated),
            "    total numeric GENERATED ALWAYS AS ((price * qty)) STORED"
        );
    }

    #[test]
    fn a_partitioned_table_and_one_of_its_partitions() {
        let mut parent = table(vec![col("at", "date", true)]);
        parent.qualified_name = "public.events".into();
        parent.partition_key = Some("RANGE (at)".into());
        assert_eq!(
            create_statement(&parent),
            "CREATE TABLE public.events (\n    at date NOT NULL\n) PARTITION BY RANGE (at);\n"
        );
        let mut child = table(vec![col("at", "date", true)]);
        child.qualified_name = "public.events_2024".into();
        child.kind = DdlKind::Partition {
            parent: "public.events".into(),
            bound: "FOR VALUES FROM ('2024-01-01') TO ('2025-01-01')".into(),
        };
        assert_eq!(
            create_statement(&child),
            "CREATE TABLE public.events_2024 PARTITION OF public.events\n\
             \x20   FOR VALUES FROM ('2024-01-01') TO ('2025-01-01');\n"
        );
        child.constraints = vec![("ck".into(), "CHECK (at > '2024-01-01'::date)".into())];
        assert_eq!(
            create_statement(&child),
            "CREATE TABLE public.events_2024 PARTITION OF public.events (\n\
             \x20   CONSTRAINT ck CHECK (at > '2024-01-01'::date)\n)\n\
             \x20   FOR VALUES FROM ('2024-01-01') TO ('2025-01-01');\n"
        );
    }

    #[test]
    fn a_view_and_a_materialized_view() {
        let mut v = table(Vec::new());
        v.qualified_name = "public.active".into();
        v.kind = DdlKind::View {
            definition: " SELECT id\n   FROM users;".into(),
            materialized: false,
        };
        assert_eq!(
            create_statement(&v),
            "CREATE VIEW public.active AS\nSELECT id\n   FROM users;\n"
        );
        v.kind = DdlKind::View {
            definition: " SELECT id\n   FROM users".into(),
            materialized: true,
        };
        v.indexes = vec!["CREATE INDEX a_id ON public.active USING btree (id)".into()];
        assert_eq!(
            create_statement(&v),
            "CREATE MATERIALIZED VIEW public.active AS\nSELECT id\n   FROM users;\n\n\
             CREATE INDEX a_id ON public.active USING btree (id);\n"
        );
    }
}
